// The site is Mongolian-only. English strings remain only as a fallback for missing keys.
export const lang = 'mn';
export const locale = 'mn-MN';

export function t(key, params = {}) {
  const text = (DICT[lang] && DICT[lang][key]) ?? DICT.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => (k in params ? String(params[k]) : `{${k}}`));
}

export function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':');
      if (attr && key) el.setAttribute(attr.trim(), t(key.trim()));
    }
  }
}

document.documentElement.lang = lang;
applyI18n();
